import React, { useEffect, useRef, useState } from 'react';
import { AnalysisResult } from '../types';
import { downloadBlob, escapeHtml, themes } from '../utils/engine';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  analysis: AnalysisResult | null;
  rawText: string;
  currentTheme: string;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  analysis,
  rawText,
  currentTheme,
}) => {
  const [includeSource, setIncludeSource] = useState(true);
  const qrRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (isOpen && analysis && qrRef.current && window.QRCode) {
      qrRef.current.innerHTML = '';
      const text = `${analysis.title} • ${analysis.wc}w • DocuWeave`;
      try {
        new window.QRCode(qrRef.current, { text, width: 160, height: 160 });
      } catch (e) {
        qrRef.current.textContent = 'QR unavailable offline';
      }
    }
  }, [isOpen, analysis]);

  if (!isOpen || !analysis) return null;

  const handleExportPage = () => {
    const webpageEl = document.getElementById('webpage');
    const clone = webpageEl ? webpageEl.outerHTML : '';
    const styleEl = document.querySelector('style') || document.querySelector('link[rel="stylesheet"]');
    const styles = styleEl ? styleEl.outerHTML : '';
    const title = analysis.title.replace(/</g, '&lt;');
    const extra = includeSource
      ? `<section style="max-width:860px;margin:18px auto;border:1px solid var(--line);border-radius:12px;padding:12px;background:#f8fafc"><h3>Source Text</h3><pre style="white-space:pre-wrap;font-size:12px;line-height:1.6">${escapeHtml(
          rawText.slice(0, 12000)
        )}</pre></section>`
      : '';
    const themeBg = themes.find((t) => t.id === currentTheme)?.bg || '#fcfaf8';
    const html = `<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${title} — DocuWeave</title><meta name="description" content="${escapeHtml(
      analysis.subtitle.slice(0, 150)
    )}"><meta property="og:title" content="${title}"><meta property="og:description" content="${escapeHtml(
      analysis.subtitle
    )}"><link href="https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,700&family=Inter:wght@400;600&display=swap" rel="stylesheet">${styles}<style>body{padding:22px;background:${themeBg}} .webpage{max-width:900px;margin:0 auto}</style></head><body>${clone}${extra}<footer style="text-align:center;color:#64748b;font-size:12px;padding:18px">Generated by DocuWeave v3 • ${new Date().toLocaleString()} • Offline</footer></body></html>`;
    downloadBlob(html, (analysis.title.slice(0, 44).replace(/[^a-z0-9]+/gi, '-') || 'docuweave') + '.html', 'text/html');
    onClose();
  };

  const handleExportMarkdown = () => {
    let md = `# ${analysis.title}\n\n*${analysis.subtitle}*\n\n> **${analysis.summaryWords}w summary • ${analysis.summaryRatio}% distilled • ${analysis.wc} words • ${analysis.readingTime} min**\n\n## Comprehensive Summary\n\n${analysis.summary}\n\n> **In one line:** ${analysis.oneLiner}\n\n## Key Points\n\n${analysis.keyPoints
      .map((p, i) => `${i + 1}. ${p.sentence}`)
      .join('\n\n')}\n\n## Important Factors\n\n${analysis.factors
      .map((f) => `### ${f.title}\n${f.evidence}\n\n*${f.cues.join(' • ')}*`)
      .join('\n\n')}\n\n## Insights\n\n**Keywords:** ${analysis.topKeywords
      .map((k) => k.term)
      .join(', ')}\n\n**Phrases:** ${analysis.topBigrams.join(
      ', '
    )}\n\n**Numbers:** ${analysis.numbers.join(', ')}\n\n**Entities:** ${analysis.entities.join(
      ', '
    )}\n\n## Stats\n\n- Words: ${analysis.wc}\n- Sentences: ${analysis.sentences}\n- Pages: ${analysis.pages}\n- Theme: ${currentTheme}\n${
      analysis.readability
        ? `- Readability: ${analysis.readability.level} (Reading Ease: ${analysis.readability.fleschReadingEase}/100, Grade Level: ${analysis.readability.fleschKincaidGrade.toFixed(1)}, Target: ${analysis.readability.audience})\n- Complexity: ${analysis.readability.avgWordsPerSentence} words/sentence, ${analysis.readability.avgSyllablesPerWord} syllables/word\n`
        : ''
    }`;
    if (includeSource) {
      md += `\n\n## Source Text\n\n\`\`\`\n${rawText.slice(0, 12000)}\n\`\`\`\n`;
    }
    downloadBlob(md, (analysis.title.slice(0, 44).replace(/[^a-z0-9]+/gi, '-') || 'docuweave') + '.md', 'text/markdown');
    onClose();
  };

  const handleExportText = () => {
    const txt = `${analysis.title}\n${'='.repeat(analysis.title.length)}\n${analysis.subtitle}\n\nSUMMARY (${
      analysis.summaryWords
    }w):\n${analysis.summary}\n\nONE LINER:\n${analysis.oneLiner}\n\nKEY POINTS:\n${analysis.keyPoints
      .map((p, i) => `${i + 1}. ${p.sentence}`)
      .join('\n')}\n\nFACTORS:\n${analysis.factors.map((f) => `- ${f.title}: ${f.evidence}`).join('\n')}\n\nREADABILITY:\n- Reading Ease: ${analysis.readability?.fleschReadingEase ?? '—'}/100 (${analysis.readability?.level ?? '—'})\n- Flesch-Kincaid Grade: ${analysis.readability?.fleschKincaidGrade ? analysis.readability.fleschKincaidGrade.toFixed(1) : '—'}\n- Target Audience: ${analysis.readability?.audience ?? '—'}\n`;
    downloadBlob(txt, (analysis.title.slice(0, 44).replace(/[^a-z0-9]+/gi, '-') || 'docuweave') + '.txt', 'text/plain');
    onClose();
  };

  const handleCopyJSON = () => {
    const j = JSON.stringify({ ...analysis, theme: currentTheme, exportedAt: new Date().toISOString() }, null, 2);
    navigator.clipboard.writeText(j).then(() => {
      alert('Copied JSON to clipboard!');
      onClose();
    });
  };

  const handleCopyJSONLD = () => {
    const ld = {
      '@context': 'https://schema.org',
      '@type': 'Article',
      headline: analysis.title,
      description: analysis.subtitle,
      articleBody: analysis.summary,
      keywords: analysis.topKeywords.map((k) => k.term).join(', '),
      wordCount: analysis.wc,
      timeRequired: `PT${analysis.readingTime}M`,
      datePublished: new Date().toISOString(),
      author: { '@type': 'Organization', name: 'DocuWeave v3' },
    };
    navigator.clipboard.writeText(JSON.stringify(ld, null, 2)).then(() => {
      alert("JSON-LD (SEO) copied — paste into <script type='application/ld+json'>");
      onClose();
    });
  };

  const handleExportEmail = () => {
    const html = `<div style="font-family:Inter,sans-serif;max-width:640px;margin:0 auto"><h1 style="font-family:Fraunces,serif">${escapeHtml(
      analysis.title
    )}</h1><p style="color:#64748b">${escapeHtml(analysis.subtitle)}</p><div style="background:#f8fafc;border:1px solid #e7dfd8;border-radius:12px;padding:14px;line-height:1.6">${escapeHtml(
      analysis.summary
    )}</div><ol>${analysis.keyPoints
      .map((p) => `<li style="margin:8px 0">${escapeHtml(p.sentence)}</li>`)
      .join('')}</ol><p style="font-size:11px;color:#64748b">Generated by DocuWeave v3 • ${new Date().toLocaleString()}</p></div>`;
    navigator.clipboard.writeText(html).then(() => {
      alert('Email HTML copied to clipboard — paste into Gmail/Outlook (as HTML).');
      onClose();
    });
  };

  const handleDownloadQR = () => {
    const canvas = qrRef.current?.querySelector('canvas') || document.querySelector('#qrcode canvas');
    if (!canvas) {
      alert('QR not ready');
      return;
    }
    const a = document.createElement('a');
    a.href = (canvas as HTMLCanvasElement).toDataURL('image/png');
    a.download = 'docuweave-qr.png';
    a.click();
  };

  return (
    <div
      className="modal open"
      id="exportModal"
      onClick={(e) => {
        if (e.target === e.currentTarget) onClose();
      }}
    >
      <div className="modal-card">
        <div className="modal-head">
          <b>⬇ Export — pick a format</b>
          <button className="pill" onClick={onClose}>
            ✕
          </button>
        </div>
        <div style={{ padding: '14px', display: 'grid', gap: '10px' }}>
          <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit,minmax(180px,1fr))', gap: '10px' }}>
            <button className="btn dark" onClick={handleExportPage}>
              🌐 HTML (themed)
            </button>
            <button className="btn" onClick={handleExportMarkdown}>
              📝 Markdown
            </button>
            <button className="btn" onClick={handleExportText}>
              📄 Plain text briefing
            </button>
            <button className="btn" onClick={handleCopyJSON}>
              {'{}'} JSON
            </button>
            <button className="btn" onClick={handleCopyJSONLD}>
              🔗 JSON-LD (SEO)
            </button>
            <button className="btn" onClick={handleExportEmail}>
              ✉️ Email HTML
            </button>
          </div>
          <div
            style={{
              border: '1px solid var(--line)',
              borderRadius: '12px',
              padding: '12px',
              display: 'flex',
              gap: '12px',
              alignItems: 'center',
              flexWrap: 'wrap',
              background: '#f8fafc',
            }}
          >
            <div
              id="qrLarge"
              ref={qrRef}
              style={{ background: '#fff', padding: '8px', border: '1px solid var(--line)', borderRadius: '12px' }}
            />
            <div>
              <b style={{ fontSize: '13px' }}>QR for this webpage</b>
              <p style={{ margin: '4px 0 0', fontSize: '12px', color: 'var(--muted)', maxWidth: '320px' }}>
                Share the exported HTML via any host — this QR encodes the page title + a data hint. For fully offline share, export HTML and host it.
              </p>
              <button className="btn small" onClick={handleDownloadQR}>
                Download QR PNG
              </button>
            </div>
          </div>
          <label style={{ display: 'flex', alignItems: 'center', gap: '8px', fontSize: '12px', fontWeight: 600 }}>
            <input
              type="checkbox"
              id="includeSource"
              checked={includeSource}
              onChange={(e) => setIncludeSource(e.target.checked)}
            />{' '}
            Include source text in exports
          </label>
        </div>
      </div>
    </div>
  );
};
